export function beersForHouse(houseId) {
  return BEERS.filter((beer) => beer.house === houseId);
}

export function beersForMood(moodId) {
  return BEERS.filter((beer) => beer.mood.includes(moodId));
}

export function houseById(id) {
  return HOUSES.find((h) => h.id === id);
}

export function scoreQuiz(answers) {
  const scores = {};
  let houseHint = null;
  answers.forEach((ans, i) => {
    const opt = QUIZ[i].options.find((o) => o.id === ans);
    if (!opt) return;
    if (opt.house) houseHint = opt.house;
    (opt.tags || []).forEach((tag) => {
      scores[tag] = (scores[tag] || 0) + 1;
    });
  });
  const ranked = BEERS.map((beer) => {
    let score = beer.mood.reduce((acc, m) => acc + (scores[m] || 0), 0);
    if (scores.session && beer.strength === "session") score += 2;
    if (scores.bold && beer.strength === "strong") score += 2;
    if (scores.strong && beer.strength === "strong") score += 2;
    if (houseHint && beer.house === houseHint) score += 3;
    return { beer, score };
  }).sort((a, b) => b.score - a.score);
  return ranked[0].beer;
}
